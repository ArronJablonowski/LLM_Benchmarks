"""Shared, deterministic image handling for agent-path OCR benchmarks."""
from __future__ import annotations

import base64
import hashlib
from pathlib import Path


VISION_CAPABILITIES = frozenset({"image", "vision", "ocr"})
OCR_MIME_TYPE = "image/png"


def model_supports_vision(model: dict) -> bool:
    """Return true only when frozen/discovered metadata advertises vision."""
    capabilities = {
        str(capability).strip().lower()
        for capability in model.get("capabilities") or []
    }
    return bool(capabilities & VISION_CAPABILITIES)


def materialize_ocr_asset(task: dict, encoded_png: str, output_dir: Path) -> dict:
    """Persist the exact synthetic OCR image and return reproducibility data."""
    if not task.get("requires_image"):
        raise ValueError(f"Task {task.get('id')!r} is not an image task")
    raw = base64.b64decode(encoded_png, validate=True)
    if not raw.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError("OCR fixture is not a PNG")
    digest = hashlib.sha256(raw).hexdigest()
    asset_dir = output_dir.expanduser() / "assets"
    asset_dir.mkdir(parents=True, exist_ok=True)
    path = asset_dir / f"{task['id']}-{digest[:16]}.png"
    if path.exists() and path.read_bytes() != raw:
        raise RuntimeError(f"Existing OCR fixture does not match generated bytes: {path}")
    if not path.exists():
        path.write_bytes(raw)
    return {
        "path": str(path.resolve()),
        "sha256": digest,
        "mime_type": OCR_MIME_TYPE,
        "bytes": len(raw),
        "base64": encoded_png,
    }
